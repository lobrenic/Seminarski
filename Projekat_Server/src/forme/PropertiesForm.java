    private void loadProps() {
        try {
            props=new Properties();
            InputStream in = Konekcija.class.getClassLoader().getResourceAsStream("baza/config.properties");
            props.load(in);
            jTextFieldDatabase.setText(props.getProperty("database"));
            jTextFieldUser.setText(props.getProperty("user"));
            jTextFieldPassword.setText(props.getProperty("password"));
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Greska pri ucitavanju podataka");
        }
    }
