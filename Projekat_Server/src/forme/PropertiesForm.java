    private void jButtonSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSacuvajActionPerformed
        String database=jTextFieldDatabase.getText();
        String user=jTextFieldUser.getText();
        String pass=jTextFieldPassword.getText();
        
        if (database == null || database.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Database ne sme biti prazan!");
            return;
        }

        if (user == null || user.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "User ne sme biti prazan!");
            return;
        }
        
        
        try {
            props=new Properties();
            props.setProperty("database", database);
            props.setProperty("user", user);
            props.setProperty("password", pass);
            String projectPath = System.getProperty("user.dir");
            String filePath = projectPath + "/src/baza/config.properties";
            FileOutputStream out=new FileOutputStream(filePath);
            props.store(out, "Database Configuration");
            out.close();
            Konekcija.getInstance().reconnect();
            JOptionPane.showMessageDialog(this, "Sačuvano!");
            
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška: " + ex.getMessage(), "Greška", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jButtonSacuvajActionPerformed

