    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
        String username=jTextFieldUsername.getText();
        String password=String.valueOf(jPasswordFieldPassword.getPassword());
        
        if(username==null || username.equals("") || password==null || password.equals("")){
            JOptionPane.showMessageDialog(this, "Unesite pravilno polja za prijavu!");
            return;
        }
        
        KlijentskiZahtev kz=new KlijentskiZahtev(new Prodavac(-1, null, null, username, password, null), Operacije.LOGIN);
        Controller.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage(), "Greška", JOptionPane.ERROR_MESSAGE);
            return;
        }
    Prodavac p=(Prodavac) so.getParam();
        if(p.getId()==-1){
            JOptionPane.showMessageDialog(this, "Korisnicko ime i/ili sifra nisu ispravni!","Greška",JOptionPane.ERROR_MESSAGE);
            return;
        }
        Controller.getInstance().setUlogovani(p);
        JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra su ispravni!");
        GlavnaForma gf=new GlavnaForma();
        gf.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_jButtonLoginActionPerformed

    private void jButtonOdjavaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonOdjavaActionPerformed
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.LOGOFF));
        if((Boolean)Controller.getInstance().primiOdgovor().getParam()){
            Komunikacija.getInstance().close();
            this.dispose();
        }
    }//GEN-LAST:event_jButtonOdjavaActionPerformed

