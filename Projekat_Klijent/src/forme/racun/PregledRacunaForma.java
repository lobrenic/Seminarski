    private void jButtonFiltrirajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonFiltrirajActionPerformed
        int id=-1;
        if(!jTextFieldBrojRacuna.getText().equals("")){
            if(!isNumber(jTextFieldBrojRacuna.getText())){
                JOptionPane.showMessageDialog(this, "Sifra mora biti ceo broj");
                return;
            }
            id=Integer.parseInt(jTextFieldBrojRacuna.getText());
        }
        
        Kupac k=(Kupac) jComboBoxKupci.getSelectedItem();
        System.out.println(k);
        Prodavac p= (Prodavac) jComboBoxProdavac.getSelectedItem();
        System.out.println(p);
        System.out.println(id);
                
        
        filtrirani.clear();
        filtrirani.addAll(svi);
        
        filtrirajPoKupcu(k);
        filtrirajPoProdavcu(p);
        filtrirajPoRacunu(id);
        
        osveziTabelu();
        if(filtrirani.isEmpty()){
            JOptionPane.showMessageDialog(this, "Sistem ne može da nađe račune po zadatim kriterijumima","Greška",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonFiltrirajActionPerformed

