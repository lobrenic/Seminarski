    public void popuniTabelu() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_RACUNI));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        svi=(ArrayList<Racun>) so.getParam();
        filtrirani=new ArrayList<>(svi);
        ModelTabeleRacun mtr=new ModelTabeleRacun(filtrirani);
        jTableRacuni.setModel(mtr);
    }

    private void popuniComboBoxeve() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_KUPCI));
        ServerskiOdgovor so1=Controller.getInstance().primiOdgovor();
        if(so1.getException()!=null){
            JOptionPane.showMessageDialog(this, so1.getException().getMessage());
            return;
        }
        kupci=(ArrayList<Kupac>) so1.getParam();
        
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_PRODAVCI));
        ServerskiOdgovor so2=Controller.getInstance().primiOdgovor();
        if(so2.getException()!=null){
            JOptionPane.showMessageDialog(this, so2.getException().getMessage());
            return;
        }
        prodavci=(ArrayList<Prodavac>) so2.getParam();
        
        for (Kupac k : kupci) {
            jComboBoxKupci.addItem(k);
        }
        jComboBoxKupci.setSelectedIndex(-1);
        
        for (Prodavac p : prodavci) {
            jComboBoxProdavac.addItem(p);
        }
        jComboBoxProdavac.setSelectedIndex(-1);
               
    }
    
    private boolean isNumber(String text) {
        for(int i=0;i<text.trim().length();i++){
            if(Character.isAlphabetic(text.trim().charAt(i))){
                return false;
            }
        }
        return true;
    }

    private void filtrirajPoKupcu(Kupac k) {
        if(jComboBoxKupci.getSelectedIndex()==-1){
            return;
        }
        ArrayList<Racun> help=new ArrayList<>();
        for (Racun r : filtrirani) {
            if(r.getKupac().equals(k)){
                help.add(r);
            }
        }
        filtrirani.clear();
        filtrirani.addAll(help);
    }

    private void filtrirajPoProdavcu(Prodavac p) {
        if(jComboBoxProdavac.getSelectedIndex()==-1){
            return;
        }
        ArrayList<Racun> help=new ArrayList<>();
        for (Racun r : filtrirani) {
            if(r.getProdavac().equals(p)){
                help.add(r);
            }
        }
        filtrirani.clear();
        filtrirani.addAll(help);
    }
    
    private void filtrirajPoRacunu(int id) {
        if(id==-1){
            return;
        }
        ArrayList<Racun> help=new ArrayList<>();
        for (Racun r : filtrirani) {
            if(r.getId()==id){
                help.add(r);
            }
        }
        filtrirani.clear();
        filtrirani.addAll(help);
    }

    public void osveziTabelu() {
        ((ModelTabeleRacun)jTableRacuni.getModel()).fireTableDataChanged();
    }

    public void ukloniFiltere() {
        filtrirani.clear();
        filtrirani.addAll(svi);
        osveziTabelu();
        jComboBoxKupci.setSelectedIndex(-1);
        jComboBoxProdavac.setSelectedIndex(-1);
        jTextFieldBrojRacuna.setText("");
    }
    
