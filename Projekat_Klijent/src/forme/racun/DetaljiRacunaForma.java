    private void popuniTextFieldove() {
        jTextFieldBrojRacuna.setText(racun.getBrojRacuna());
        jTextFieldDatum.setText(racun.getCreatedAt().format(DateTimeFormatter.ofPattern("dd.MM.yyyy")));
        jTextFieldKupac.setText(racun.getKupac().toString());
        jTextFieldProdavac.setText(racun.getProdavac().toString());
        jTextFieldUkupanIznos.setText(String.valueOf(racun.getUkupanIznos()));
        
        
    }
    
    public void osveziPrikaz(Racun noviRacun) {
        this.racun = noviRacun;
        popuniTextFieldove();
        popuniTabelu();
    }
    private void popuniTabelu() {
        ModelTabeleStavke tms= new ModelTabeleStavke(racun.getStavka());
        jTableStavke.setModel(tms);
    }
