    private void jButtonDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDodajActionPerformed
        if(jTextFieldKolicina.getText()==null || jTextFieldKolicina.getText().equals("")
                || !isNumber(jTextFieldKolicina.getText()) || jComboBoxProizvodi.getSelectedIndex()==-1 ||
                Integer.parseInt(jTextFieldKolicina.getText())<=0){
            JOptionPane.showMessageDialog(this, "Greska pri unosu podataka!");
            return;
        }
        
        Oprema o=(Oprema) jComboBoxProizvodi.getSelectedItem();
        
        int kolicina=Integer.parseInt(jTextFieldKolicina.getText());
        double cena=o.getCena();
        double iznos=cena*kolicina;
        StavkaRacuna sr=new StavkaRacuna(stavke.size()+1, kolicina, cena, iznos, o,racun.getId());
        stavke.add(sr);
        osveziTabelu();
        izracunajUkupno();
        jTextFieldKolicina.setText("0");
        jComboBoxProizvodi.setSelectedIndex(-1);
    }//GEN-LAST:event_jButtonDodajActionPerformed

    private void jButtonObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonObrisiActionPerformed
        int row=jTable1.getSelectedRow();
        if(row==-1){
            JOptionPane.showMessageDialog(this, "Izaberite stavku za brisanje!");
            return;
        }
        stavke.remove(row);
        renumerisiStavke();
        osveziTabelu();
        izracunajUkupno();
    }//GEN-LAST:event_jButtonObrisiActionPerformed

    private void jButtonSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSacuvajActionPerformed
        
       
        if(stavke.isEmpty() || jComboBoxKupci.getSelectedIndex()==-1){
            JOptionPane.showMessageDialog(this, "Proverite da li ste dodali stavke i da li je kupac ispravan");
            return;
        }
        racun.setBrojRacuna(jTextFieldBrojRacuna.getText());
        racun.setKupac((Kupac)jComboBoxKupci.getSelectedItem());
        racun.setCreatedAt(LocalDate.parse(jTextFieldCreatedAt.getText(),DateTimeFormatter.ofPattern("dd.MM.yyyy")));
        racun.setStatus(StatusRacun.ISSUED);
        racun.setStavka(stavke);
        racun.setUkupanIznos(Double.parseDouble(jTextFieldUkupno.getText()));
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(racun, Operacije.ISSUE_RACUN));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        boolean uspeh=(boolean)so.getParam();
        if(!uspeh){
            JOptionPane.showMessageDialog(this, "Sistem ne može da zapamti račun!","Greška",JOptionPane.ERROR_MESSAGE);
            return;
        }
        JOptionPane.showMessageDialog(this, "Sistem je zapamtio racun!");
        if(pregled!=null){
            pregled.popuniTabelu();
            pregled.ukloniFiltere();
        }
        if(detalji!=null){
            detalji.osveziPrikaz(racun);
        }
        this.dispose();
    }//GEN-LAST:event_jButtonSacuvajActionPerformed

