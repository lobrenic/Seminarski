    private void popuniComboBoxeve() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_KUPCI));
        ServerskiOdgovor so1=Controller.getInstance().primiOdgovor();
        if(so1.getException()!=null){
            JOptionPane.showMessageDialog(this, so1.getException().getMessage());
            return;
        }
        kupci=(ArrayList<Kupac>) so1.getParam();
        
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_OPREMA));
        ServerskiOdgovor so2=Controller.getInstance().primiOdgovor();
        if(so2.getException()!=null){
            JOptionPane.showMessageDialog(this, so2.getException().getMessage());
            return;
        }
        oprema=(ArrayList<Oprema>) so2.getParam();
        
        for (Oprema o : oprema) {
            jComboBoxProizvodi.addItem(o);
        }
        jComboBoxProizvodi.setSelectedIndex(-1);
        
        for (Kupac k : kupci) {
            jComboBoxKupci.addItem(k);
        }
        jComboBoxKupci.setSelectedIndex(-1);
        
    }

    private void generisiBrojRacuna() {
        String brojRacuna=jTextFieldCreatedAt.getText().replaceAll("\\.", "")+"/"+racun.getId();
        jTextFieldBrojRacuna.setText(brojRacuna);
                
    }

    private void popuniDatum() {
        jTextFieldCreatedAt.setText(LocalDate.now().format(DateTimeFormatter.ofPattern("dd.MM.yyyy")));
    }

    private void zauzmiProstor() {
        
        racun=new Racun(-1, null, ulogovani, null, null,
                0, StatusRacun.DRAFT,
                LocalDate.parse(jTextFieldCreatedAt.getText(),DateTimeFormatter.ofPattern("dd.MM.yyyy")));
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(racun, Operacije.DECLARATION_RACUN));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            this.dispose();
            return;
        }
        racun=(Racun) so.getParam();
        if(racun.getId()==-1){
            JOptionPane.showMessageDialog(this,"Sistem ne može da kreira račun","Greška",JOptionPane.ERROR_MESSAGE);
            this.dispose();
            return;
        }
        JOptionPane.showMessageDialog(this, "Sistem je kreirao racun");
        
    }

    private boolean isNumber(String text) {
        for(int i=0;i<text.trim().length();i++){
            if(Character.isAlphabetic(text.trim().charAt(i))){
                return false;
            }
        }
        return true;
    }

    private void popuniTabelu() {
        ModelTabeleStavke tms=new ModelTabeleStavke(stavke);
        jTable1.setModel(tms);
    }
    
    private void osveziTabelu(){
        ((ModelTabeleStavke)jTable1.getModel()).fireTableDataChanged();
    }

    private void izracunajUkupno() {
        double ukupanIznos=0;
        for (StavkaRacuna s : stavke) {
           ukupanIznos+=s.getIznos();
        }
        jTextFieldUkupno.setText(String.format("%.2f", ukupanIznos));
    }

    private void popuniPodatkeRacun() {
        jComboBoxKupci.setSelectedItem(racun.getKupac());
        jTextFieldCreatedAt.setText(racun.getCreatedAt().format(DateTimeFormatter.ofPattern("dd.MM.yyyy")));
        jTextFieldBrojRacuna.setText(racun.getBrojRacuna());
        jTextFieldUkupno.setText(racun.getUkupanIznos()+"");
        stavke.clear();
        stavke.addAll(racun.getStavka());
        osveziTabelu();
    }
    

    private void otkazi() {
        int choice=JOptionPane.showConfirmDialog(this, "Da li bi ste zeleli da sacuvate racun za kasnije?");
        if(choice==JOptionPane.NO_OPTION){
            if(pregled!=null){
                this.dispose();
                return;
            }
            Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(racun, Operacije.ABORT_RACUN));
            ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
            if(so.getException()!=null){
                JOptionPane.showMessageDialog(this, so.getException().getMessage());
                this.dispose();
                return;
            }
            boolean uspeh=(boolean)so.getParam();
            if(!uspeh){
                JOptionPane.showMessageDialog(this, "Doslo je do greske!");
                return;
            }
            this.dispose();
            return;
        }
        if(choice==JOptionPane.YES_OPTION){
            racun.setBrojRacuna(jTextFieldBrojRacuna.getText());
            if(jComboBoxKupci.getSelectedIndex()!=-1)
                racun.setKupac((Kupac)jComboBoxKupci.getSelectedItem());
            racun.setCreatedAt(LocalDate.parse(jTextFieldCreatedAt.getText(),DateTimeFormatter.ofPattern("dd.MM.yyyy")));
            racun.setStatus(StatusRacun.DRAFT);
            
            racun.setStavka(stavke);
            racun.setUkupanIznos(Double.parseDouble(jTextFieldUkupno.getText()));
            System.out.println(racun);
            Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(racun, Operacije.ISSUE_RACUN));
            ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
            if(so.getException()!=null){
                JOptionPane.showMessageDialog(this, so.getException().getMessage());
                return;
            }
            boolean uspeh=(boolean)so.getParam();
            if(!uspeh){
                JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti racun!");
                return;
            }
            if(pregled!=null){
                pregled.popuniTabelu();
                pregled.ukloniFiltere();
            }
            if(detalji!=null){
                detalji.osveziPrikaz(racun);
            }
            this.dispose();
        }}

    private void renumerisiStavke() {
        stavke.sort(Comparator.comparing(StavkaRacuna::getRedniBroj));
        int brojac=1;
        for (StavkaRacuna sr : stavke) {
            sr.setRedniBroj(brojac);
            brojac++;
        }
    }
