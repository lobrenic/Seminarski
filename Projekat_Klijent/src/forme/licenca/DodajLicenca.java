    private void popuniComboBoxeve() {
        TipLicence[] tipovi=TipLicence.values();
        for (TipLicence tipLicence : tipovi) {
            jComboBoxTip.addItem(tipLicence);
        }
        jComboBoxTip.setSelectedIndex(-1);
        
        TrzisnaMarka[] marke=TrzisnaMarka.values();
        for (TrzisnaMarka m : marke) {
            jComboBoxTrzisnaMarka.addItem(m);
        }
        jComboBoxTrzisnaMarka.setSelectedIndex(-1);
    }

    private void zauzmiProstor() {
        licenca=new Licenca(-1, null, null, null, null);
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(licenca, Operacije.DECLARATION_LICENCA));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        licenca=(Licenca) so.getParam();
        JOptionPane.showMessageDialog(this, "Licenca kreirana");
        
    }

    private boolean validacija() {
        if(jComboBoxTip.getSelectedIndex()==-1){
            JOptionPane.showMessageDialog(this, "Izaberite tip licence");
            return false;
        }
        if(jComboBoxTrzisnaMarka.getSelectedIndex()==-1){
            JOptionPane.showMessageDialog(this, "Izaberite trzisnu marku");
            return false;
        }
        if(jTextFieldBrend.getText()==null || jTextFieldBrend.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite brend");
            return false;
        }
        if(jTextFieldLicencor.getText()==null || jTextFieldLicencor.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite licencora");
            return false;
        }
        return true;
    }

    private void otkazi() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(licenca, Operacije.ABORT_LICENCA));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            this.dispose();
            return;
        }
        boolean success=(boolean)so.getParam();
        if(!success){
            JOptionPane.showMessageDialog(this, "Došlo je do greške");
            this.dispose();
            return;
        }
        this.dispose();
    }
