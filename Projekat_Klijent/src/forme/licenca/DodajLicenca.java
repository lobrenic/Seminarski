    private void jButtonDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDodajActionPerformed
        
        if(!validacija())
            return;
        licenca.setBrend(jTextFieldBrend.getText());
        licenca.setLicencor(jTextFieldLicencor.getText());
        licenca.setTrzisnaMarka((TrzisnaMarka) jComboBoxTrzisnaMarka.getSelectedItem());
        licenca.setTip((TipLicence) jComboBoxTip.getSelectedItem());
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(licenca, Operacije.SAVE_LICENCA));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        if(!(boolean)so.getParam()){
            JOptionPane.showMessageDialog(this, "Sistem ne može da zapamti licencu", "Greška",JOptionPane.ERROR_MESSAGE);
        }
        JOptionPane.showMessageDialog(this, "Sistem je zapamtio licencu");
        this.dispose();
    }//GEN-LAST:event_jButtonDodajActionPerformed

