    private void jButtonSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSacuvajActionPerformed
        
        if(!validacija())
            return;
        
        kupac.setIme(jTextFieldIme.getText());
        kupac.setPrezime(jTextFieldPrezime.getText());
        kupac.setTelefon(jTextFieldTelefon.getText());
        kupac.setUlica(jTextFieldUlica.getText());
        kupac.setBroj(Integer.parseInt(jTextFieldBroj.getText()));
        kupac.setMesto((Mesto) jComboBoxMesto.getSelectedItem());
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(kupac, Operacije.SAVE_KUPAC));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        boolean success=(boolean) so.getParam();
        if(!success){
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti kupca","Greška",JOptionPane.ERROR_MESSAGE);
            return;
        }
        JOptionPane.showMessageDialog(this, "Sistem je zapamtio kupca");
        if(parent!=null){
            parent.popuniTabelu();
            parent.ukloniFiltere();
        }
        this.dispose();
    }//GEN-LAST:event_jButtonSacuvajActionPerformed

