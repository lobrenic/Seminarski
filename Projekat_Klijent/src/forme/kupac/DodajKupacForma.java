    private void popuniComboBox() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_MESTA));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        List<Mesto> mesta=(List<Mesto>) so.getParam();
        
        for (Mesto m : mesta) {
            jComboBoxMesto.addItem(m);
        }
        jComboBoxMesto.setSelectedIndex(-1);
    }

    private void zauzmiProstor() {
        kupac=new Kupac(-1, null, null, null, null, -1, null);
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(kupac, Operacije.DECLARATION_KUPAC));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            this.dispose();
            return;
        }
        kupac=(Kupac)so.getParam();
        if(kupac.getId()==-1){
            JOptionPane.showMessageDialog(this, "Sistem ne može da kreira kupca!");
            this.dispose();
            return;
        }
        JOptionPane.showMessageDialog(this, "Sistem je kreirao kupca");
    }

    private boolean validacija() {
        
        if(jTextFieldIme.getText()==null || jTextFieldIme.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite ime kupca");
            return false;
        }
        if(jTextFieldPrezime.getText()==null || jTextFieldPrezime.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite prezime kupca");
            return false;
        }
        if(jTextFieldTelefon.getText()==null || jTextFieldTelefon.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite broj telefona kupca");
            return false;
        }
        if(jTextFieldUlica.getText()==null || jTextFieldUlica.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite kompletnu adresu kupca");
            return false;
        }
        if(jTextFieldBroj.getText()==null || jTextFieldIme.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite kompletnu adresu kupca");
            return false;
        }
        if(jComboBoxMesto.getSelectedIndex()==-1){
            JOptionPane.showMessageDialog(this, "Izaberite grad stanovanja kupca");
            return false;
        }
        return true;    
    }

    private void popuniPodatke() {
        jTextFieldIme.setText(kupac.getIme());
        jTextFieldPrezime.setText(kupac.getPrezime());
        jTextFieldTelefon.setText(kupac.getTelefon());
        jTextFieldUlica.setText(kupac.getUlica());
        jTextFieldBroj.setText(String.valueOf(kupac.getBroj()));
        jComboBoxMesto.setSelectedItem(kupac.getMesto());
    }

    private void enableEdit() {
        jButtonSacuvaj.setVisible(true);
        jButtonIzmeni.setVisible(false);
        jTextFieldIme.setEnabled(true);
        jTextFieldPrezime.setEnabled(true);
        jTextFieldTelefon.setEnabled(true);
        jTextFieldUlica.setEnabled(true);
        jTextFieldBroj.setEnabled(true);
        jComboBoxMesto.setEnabled(true);}

    private void disableEdit() {
        jButtonSacuvaj.setVisible(false);
        
            jTextFieldIme.setEnabled(false);
            jTextFieldPrezime.setEnabled(false);
            jTextFieldTelefon.setEnabled(false);
            jTextFieldUlica.setEnabled(false);
            jTextFieldBroj.setEnabled(false);
            jComboBoxMesto.setEnabled(false);}

    private void otkazi() {
        if(parent!=null){
            this.dispose();
            return;
        }
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(kupac, Operacije.ABORT_KUPAC));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            this.dispose();
            return;
        }
        boolean success=(boolean)so.getParam();
        if(!success){
            JOptionPane.showMessageDialog(this, "Doslo je do greske");
            this.dispose();
            return;
        }
        this.dispose();
    }
