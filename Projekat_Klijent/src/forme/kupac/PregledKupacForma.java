    public void popuniTabelu() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null,Operacije.GET_ALL_KUPCI));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        svi=(List<Kupac>) so.getParam();
        filtrirani=new ArrayList<>(svi);
        ModelTabeleKupac mtk=new ModelTabeleKupac(filtrirani);
        jTableKupci.setModel(mtk);
    }

    private void popuniComboBox() {
        Controller.getInstance().posaljiZahtev(new KlijentskiZahtev(null, Operacije.GET_ALL_MESTA));
        ServerskiOdgovor so=Controller.getInstance().primiOdgovor();
        if(so.getException()!=null){
            JOptionPane.showMessageDialog(this, so.getException().getMessage());
            return;
        }
        List<Mesto> mesta=(List<Mesto>) so.getParam();
        
        for (Mesto m : mesta) {
            jComboBoxMesto.addItem(m);
        }
        jComboBoxMesto.setSelectedIndex(-1);
    }
    
    public void osveziTabelu() {
        ((ModelTabeleKupac)jTableKupci.getModel()).fireTableDataChanged();
    }
    
    private boolean isNumber(String text) {
        for(int i=0;i<text.trim().length();i++){
            if(Character.isAlphabetic(text.trim().charAt(i))){
                return false;
            }
        }
        return true;
    }

    private void filtrirajPoImenu() {
        if(jTextFieldIme.getText()==null || jTextFieldIme.getText().equals("")){
            return;
        }
        List<Kupac> help=new ArrayList<>();
        for (Kupac k : filtrirani) {
            if(k.getIme().trim().toUpperCase().equals(jTextFieldIme.getText().trim().toUpperCase()))
                help.add(k);
        }
        
        filtrirani.clear();
        filtrirani.addAll(help);
    }

    private void filtrirajPoPrezimenu() {
        if(jTextFieldPrezime.getText()==null || jTextFieldPrezime.getText().equals("")){
            return;
        }
        List<Kupac> help=new ArrayList<>();
        for (Kupac k : filtrirani) {
            if(k.getPrezime().trim().toUpperCase().equals(jTextFieldPrezime.getText().trim().toUpperCase()))
                help.add(k);
        }
        
        filtrirani.clear();
        filtrirani.addAll(help);
    }

    private void filtrirajPoMestu() {
        if(jComboBoxMesto.getSelectedIndex()==-1)
            return;
        List<Kupac> help=new ArrayList<>();
        for (Kupac k : filtrirani) {
            if(k.getMesto().equals(jComboBoxMesto.getSelectedItem())){
                help.add(k);
            }
        }
        filtrirani.clear();
        filtrirani.addAll(help);
    }

    public void ukloniFiltere() {
        filtrirani.clear();
        filtrirani.addAll(svi);
        osveziTabelu();
        jTextFieldIme.setText("");
        jTextFieldPrezime.setText("");
        jComboBoxMesto.setSelectedIndex(-1);
    }
